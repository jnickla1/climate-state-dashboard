/* Translation support for the climate state dashboard (20 Oct 2026).
   British English (en-GB) is the source language and is bundled in i18n/en-GB.js, so
   t() works immediately. Other languages are i18n/<code>.json files registered in
   i18n/locales.js (both generated by source/build_i18n.py); they load before the app starts.
   Language choice: ?lang=<code>, then a previously chosen language, then the browser's
   languages, then en-GB. A language menu appears only when more than one is registered. */
'use strict';
window.I18N = (() => {
  const SOURCE = 'en-GB';
  const bundles = window.I18N_BUNDLES || {};
  const registry = window.I18N_LOCALES || { [SOURCE]: { name: 'English (UK)', dir: 'ltr' } };
  const STORE = 'climateStateLang';
  const source = (bundles[SOURCE] || {}).strings || {};
  let strings = source, lang = SOURCE, meta = registry[SOURCE] || {};

  function pick() {
    const codes = Object.keys(registry);
    const match = want => {
      if (!want) return null;
      const lower = want.toLowerCase();
      return codes.find(c => c.toLowerCase() === lower) ||
        codes.find(c => c.toLowerCase().split('-')[0] === lower.split('-')[0]) || null;
    };
    const fromUrl = match(new URLSearchParams(location.search).get('lang'));
    if (fromUrl) return fromUrl;
    try { const saved = match(localStorage.getItem(STORE)); if (saved) return saved; } catch (e) { /* storage unavailable */ }
    for (const l of navigator.languages || [navigator.language]) { const m = match(l); if (m) return m; }
    return SOURCE;
  }

  // {name} placeholders; Plotly's %{x} templates are left alone.
  function fill(text, vars) {
    return vars ? text.replace(/(^|[^%])\{(\w+)\}/g, (all, pre, k) => pre + (k in vars ? vars[k] : '{' + k + '}')) : text;
  }
  function t(key, vars) {
    const text = key in strings ? strings[key] : key in source ? source[key] : key;
    return fill(text, vars);
  }
  // Text that comes with the data (method labels, notes): translated only when a locale provides it.
  function tData(key, fallback, vars) {
    return lang !== SOURCE && key in strings ? fill(strings[key], vars) : fallback;
  }

  const formatters = new Map();
  function num(x, digits) {
    if (!Number.isFinite(x)) return t('number.pending');
    if (lang === SOURCE) return x.toFixed(digits);
    const key = digits;
    if (!formatters.has(key)) formatters.set(key, new Intl.NumberFormat(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false }));
    return formatters.get(key).format(x);
  }
  function pct(p, digits) {
    if (lang === SOURCE) return (100 * p).toFixed(digits) + '%';
    return new Intl.NumberFormat(lang, { style: 'percent', minimumFractionDigits: digits, maximumFractionDigits: digits }).format(p);
  }
  // Plotly's decimal and thousands characters; undefined keeps Plotly's default for en-GB.
  function separators() {
    if (lang === SOURCE) return undefined;
    const parts = new Intl.NumberFormat(lang).formatToParts(12345.6);
    return (parts.find(p => p.type === 'decimal') || { value: '.' }).value + (parts.find(p => p.type === 'group') || { value: ',' }).value;
  }

  function applyStatic(root = document) {
    if (lang === SOURCE) return; // the HTML is written in en-GB
    for (const el of root.querySelectorAll('[data-i18n]')) {
      const key = el.getAttribute('data-i18n');
      if (key in strings) el.innerHTML = strings[key];
    }
    for (const el of root.querySelectorAll('[data-i18n-attr]')) {
      for (const pair of el.getAttribute('data-i18n-attr').split(';')) {
        const [attr, key] = pair.split(':');
        if (key in strings) el.setAttribute(attr, strings[key]);
      }
    }
    if ('doc.title' in strings) document.title = strings['doc.title'];
    const desc = document.querySelector('meta[name=description]');
    if (desc && 'doc.description' in strings) desc.content = strings['doc.description'];
  }

  function addMenu() {
    const codes = Object.keys(registry);
    if (codes.length < 2 || document.getElementById('langSelect')) return;
    const label = document.createElement('label');
    label.className = 'lang-menu';
    const span = document.createElement('span');
    span.className = 'visually-hidden';
    span.textContent = t('lang.label');
    const select = document.createElement('select');
    select.id = 'langSelect';
    for (const code of codes) {
      const o = document.createElement('option');
      o.value = code; o.textContent = registry[code].name || code; o.lang = code;
      select.append(o);
    }
    select.value = lang;
    select.addEventListener('change', () => {
      try { localStorage.setItem(STORE, select.value); } catch (e) { /* storage unavailable */ }
      const q = new URLSearchParams(location.search); q.set('lang', select.value);
      location.search = q.toString();
    });
    label.append(span, select);
    // Join the header's right-hand buttons (tour.js adds the Tour button to the same group).
    const paper = document.querySelector('header .paper-link');
    if (!paper) { document.querySelector('header')?.append(label); return; }
    let wrap = paper.closest('.header-actions');
    if (!wrap) { wrap = document.createElement('div'); wrap.className = 'header-actions'; paper.parentNode.insertBefore(wrap, paper); wrap.append(paper); }
    wrap.insertBefore(label, wrap.firstChild);
  }

  const ready = (async () => {
    const want = pick();
    if (want !== SOURCE) {
      try {
        const r = await fetch('i18n/' + want + '.json?v=' + (registry[want].version || '1'));
        if (!r.ok) throw new Error(r.status);
        const bundle = await r.json();
        strings = bundle.strings || {}; lang = want; meta = registry[want];
      } catch (e) { console.warn('Could not load language ' + want + '; using ' + SOURCE + '.', e); }
    }
    const dom = () => {
      if (lang !== SOURCE) { document.documentElement.lang = lang; document.documentElement.dir = meta.dir || 'ltr'; }
      applyStatic(); addMenu();
    };
    if (document.readyState === 'loading') await new Promise(r => document.addEventListener('DOMContentLoaded', r, { once: true }));
    dom();
    return lang;
  })();

  return { t, tData, num, pct, separators, ready, applyStatic, get lang() { return lang; }, get explicit() { return new URLSearchParams(location.search).has('lang'); }, SOURCE };
})();
